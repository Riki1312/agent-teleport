#!/bin/sh
# homebrew-formula.sh VERSION SHA256SUMS prints the Homebrew formula of a
# release: VERSION without its leading v, and the SHA256SUMS file that
# make dist writes. The release workflow commits it to Riki1312/homebrew-tap.
set -eu

version=$1
sums=$2
base="https://github.com/Riki1312/agent-teleport/releases/download/v$version"

# archive prints the url and sha256 lines of one platform's archive.
archive() {
	name="agent-teleport_$1.tar.gz"
	sum=$(awk -v name="$name" '$2 == name { print $1 }' "$sums")
	if [ -z "$sum" ]; then
		echo "homebrew-formula.sh: $sums lists no $name" >&2
		exit 1
	fi
	printf '      url "%s/%s"\n      sha256 "%s"\n' "$base" "$name" "$sum"
}

# Assignments stop the script when an archive is missing, before any output.
darwin_arm64=$(archive darwin_arm64)
darwin_amd64=$(archive darwin_amd64)
linux_arm64=$(archive linux_arm64)
linux_amd64=$(archive linux_amd64)

cat <<EOF
# This formula is generated by tools/homebrew-formula.sh in
# https://github.com/Riki1312/agent-teleport for each release.
class AgentTeleport < Formula
  desc "Keep coding-agent sessions in your repository and move them between machines"
  homepage "https://github.com/Riki1312/agent-teleport"
  license "MIT"

  on_macos do
    on_arm do
$darwin_arm64
    end
    on_intel do
$darwin_amd64
    end
  end

  on_linux do
    on_arm do
$linux_arm64
    end
    on_intel do
$linux_amd64
    end
  end

  def install
    bin.install "agent-teleport"
    generate_completions_from_executable(bin/"agent-teleport", "completion", shells: [:bash, :zsh])
  end

  test do
    assert_match "agent-teleport v#{version}", shell_output("#{bin}/agent-teleport --version")
  end
end
EOF
